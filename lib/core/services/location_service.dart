  /// Checks and requests device GPS location.
  static Future<Position?> requestDeviceLocation(BuildContext context) async {
    bool serviceEnabled = await Geolocator.isLocationServiceEnabled();
    if (!serviceEnabled) {
      if (context.mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(
            content: Text(
              'Location services are disabled on your device. Please turn on GPS.',
            ),
            backgroundColor: AppColors.warning,
          ),
        );
      }
      return null;
    }

    LocationPermission permission = await Geolocator.checkPermission();
    if (permission == LocationPermission.denied) {
      if (context.mounted) {
        final proceed = await showPermissionRationaleDialog(context);
        if (!proceed) return null;
      }
      permission = await Geolocator.requestPermission();
      if (permission == LocationPermission.denied) {
        if (context.mounted) {
          ScaffoldMessenger.of(context).showSnackBar(
            const SnackBar(
              content: Text(
                'Location permission denied. Using manual location.',
              ),
              backgroundColor: AppColors.warning,
            ),
          );
        }
        return null;
      }
    }

    if (permission == LocationPermission.deniedForever) {
      if (context.mounted) {
        showDialog(
          context: context,
          builder: (ctx) => AlertDialog(
            shape: RoundedRectangleBorder(
              borderRadius: BorderRadius.circular(20),
            ),
            title: const Text('Permission Permanently Denied'),
            content: const Text(
              'Location permission is permanently denied. You can enable it from system App Settings or select a city manually.',
              style: TextStyle(fontSize: 13, height: 1.4),
            ),
            actions: [
              TextButton(
                onPressed: () => Navigator.pop(ctx),
                child: const Text('Cancel'),
              ),
              ElevatedButton(
                onPressed: () {
                  Navigator.pop(ctx);
                  Geolocator.openAppSettings();
                },
                style: ElevatedButton.styleFrom(
                  backgroundColor: AppColors.primaryEmerald,
                ),
                child: const Text(
                  'Open Settings',
                  style: TextStyle(color: Colors.white),
                ),
              ),
            ],
          ),
        );
      }
      return null;
    }

    try {
      final position = await Geolocator.getCurrentPosition(
        locationSettings: const LocationSettings(
          accuracy: LocationAccuracy.high,
          timeLimit: Duration(seconds: 10),
        ),
      );
      return position;
    } catch (_) {
      try {
        return await Geolocator.getLastKnownPosition();
      } catch (_) {
        return null;
      }
    }
  }

  /// Approximate nearest city from coordinates among preset list.
  static CityPreset findNearestCity(double lat, double lng) {
    CityPreset nearest = popularIslamicCities.first;
    double minDistance = double.infinity;

    for (final c in popularIslamicCities) {
      final d = Geolocator.distanceBetween(lat, lng, c.lat, c.lng);
      if (d < minDistance) {
        minDistance = d;
        nearest = c;
      }
    }
    return nearest;
  }

  /// Resolves the IANA timezone and intelligent calculation method for given coordinates.
  static ({String ianaTimeZone, CalculationMethod defaultMethod})
      resolveLocationMetadata(
    double lat,
    double lng, {
    String city = '',
    String country = '',
  }) {
    final nearest = findNearestCity(lat, lng);
    final detectedTz = TimezoneService.detectIanaTimeZone(
      lat: lat,
      lng: lng,
      country: country.isNotEmpty ? country : nearest.country,
      city: city.isNotEmpty ? city : nearest.city,
    );

    return (
      ianaTimeZone: detectedTz,
      defaultMethod: nearest.defaultMethod,
    );
  }

