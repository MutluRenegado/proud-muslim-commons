  /// Returns localized city name based on language code.
  static String getLocalizedCity(String city, String langCode) {
    if (city.isEmpty) return city;
    final key = city.trim().toLowerCase();
    final map = _localizedCities[key];
    if (map != null && map.containsKey(langCode)) {
      return map[langCode]!;
    }
    return city;
  }

  /// Returns localized country name based on language code.
  static String getLocalizedCountry(String country, String langCode) {
    if (country.isEmpty) return country;
    final key = country.trim().toLowerCase();
    final map = _localizedCountries[key];
    if (map != null && map.containsKey(langCode)) {
      return map[langCode]!;
    }
    return country;
  }

  /// Returns formatted localized "City, Country" display string.
  static String getLocalizedLocationDisplay(
    String city,
    String country,
    String langCode,
  ) {
    final locCity = getLocalizedCity(city, langCode);
    final locCountry = getLocalizedCountry(country, langCode);
    if (locCity.isEmpty) return locCountry;
    if (locCountry.isEmpty) return locCity;
    return '$locCity, $locCountry';
  }
